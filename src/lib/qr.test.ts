describe("QR encoder", () => {
  it("matches libqrencode (version 1)", () => {
    expect(rows(encodeQr("hello", "M", 7))).toEqual(HELLO_MASK_7);
  });

  it("matches libqrencode for a setup link (version 6, two blocks)", () => {
    expect(rows(encodeQr(OTPAUTH, "M", 1))).toEqual(OTPAUTH_MASK_1);
  });

  it("picks the smallest version and a valid mask", () => {
    expect(encodeQr("hello")).toHaveLength(21);
    const auto = rows(encodeQr(OTPAUTH));
    expect(auto).toHaveLength(41);
    const masks = [0, 1, 2, 3, 4, 5, 6, 7].map((m) => rows(encodeQr(OTPAUTH, "M", m)).join("\n"));
    expect(masks).toContain(auto.join("\n"));
  });

  it("draws dark modules inside a quiet zone", () => {
    const { path, size } = qrPath(encodeQr("hello"));
    expect(size).toBe(29);
    expect(path.startsWith("M4 4h1v1h-1z")).toBe(true);
  });
});
