// A small QR code encoder (ISO/IEC 18004, byte mode) for the two-step
// verification setup link. Follows Project Nayuki's reference design; the
// output is checked against libqrencode in qr.test.ts.

export type Ecc = "L" | "M" | "Q" | "H";

const ECC_ORDINAL: Record<Ecc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECC_FORMAT_BITS: Record<Ecc, number> = { L: 1, M: 0, Q: 3, H: 2 };

